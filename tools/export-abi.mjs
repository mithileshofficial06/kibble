#!/usr/bin/env node
// Writes packages/kibble/src/abi.ts from Foundry's build output.
// The drawer's ABI is KibbleDrawer + KibbleAdmin merged: the drawer delegatecalls the admin module, so
// callers talk to one address. Run `forge build` (or `make build`) first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const load = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;

const key = (item) =>
  item.type === "function" || item.type === "event" || item.type === "error"
    ? `${item.type}:${item.name}(${(item.inputs ?? []).map((i) => i.type).join(",")})`
    : item.type;

function merge(...abis) {
  const seen = new Map();
  for (const abi of abis) {
    for (const item of abi) {
      if (item.type === "constructor" || item.type === "fallback" || item.type === "receive") continue;
      if (!seen.has(key(item))) seen.set(key(item), item);
    }
  }
  return [...seen.values()];
}

const drawerAbi = merge(load("KibbleDrawer"), load("KibbleAdmin"));
const factoryAbi = merge(load("KibbleFactory"));
const vaultAbi = merge(load("KibbleVault"));

const header = `// Generated by tools/export-abi.mjs from contracts/out. Do not edit by hand.\n// Regenerate with: make build && make abi\n\n`;
const body =
  `export const kibbleDrawerAbi = ${JSON.stringify(drawerAbi, null, 2)} as const;\n\n` +
  `export const kibbleFactoryAbi = ${JSON.stringify(factoryAbi, null, 2)} as const;\n\n` +
  `export const kibbleVaultAbi = ${JSON.stringify(vaultAbi, null, 2)} as const;\n`;

const target = join(root, "packages", "kibble", "src", "abi.ts");
writeFileSync(target, header + body);
console.log(`✓ wrote ${target} (drawer ${drawerAbi.length}, factory ${factoryAbi.length}, vault ${vaultAbi.length} entries)`);
